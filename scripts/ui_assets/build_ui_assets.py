"""Convert UI icons and images into LVGL image descriptors.

Inputs live in main/ui/assets_src/<area>/:
  *.svg  -> A8 alpha icon, tinted at runtime with the style's image_recolor colour.
            Draw with stroke/fill "currentColor" (black is fine too); size comes from the
            svg width/height attributes. Rendered by headless Chrome, so any SVG works.
  *.png  -> RGB565 if fully opaque, otherwise RGB565A8 (colour plus alpha plane).

Output: main/assets/ui_assets/<area>_assets.c and .h with one lv_image_dsc_t per file,
named ui_<area>_<path without suffix> (subfolders included, other characters become "_").

Usage: python3 scripts/ui_assets/build_ui_assets.py <area> [<area> ...]
Requires: playwright with Chrome (for SVG), Pillow.
"""
import asyncio
import io
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "main" / "ui" / "assets_src"
OUT = ROOT / "main" / "assets" / "ui_assets"


def c_name(area, rel):
    return "ui_" + re.sub(r"[^a-z0-9]+", "_", f"{area}_{rel.as_posix()}".lower()).strip("_")


async def render_svgs(paths):
    from playwright.async_api import async_playwright

    images = {}
    async with async_playwright() as p:
        browser = await p.chromium.launch(channel="chrome")
        page = await browser.new_page(device_scale_factor=1)
        for path in paths:
            svg = path.read_text()
            await page.set_content(
                "<html><body style='margin:0;background:transparent;color:#000'>"
                f"<div id='icon' style='display:inline-block;line-height:0'>{svg}</div></body></html>")
            png = await page.locator("#icon svg").screenshot(omit_background=True)
            images[path] = Image.open(io.BytesIO(png)).convert("RGBA")
        await browser.close()
    return images


def hex_rows(data, width=24):
    return ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + width])
                      for i in range(0, len(data), width))


def emit(name, img, kind):
    w, h = img.size
    if kind == "A8":
        data = img.getchannel("A").tobytes()
        cf, stride = "LV_COLOR_FORMAT_A8", w
    else:
        rgb = img.convert("RGB")
        px = bytearray()
        raw = rgb.tobytes()
        for i in range(0, len(raw), 3):
            r, g, b = raw[i], raw[i + 1], raw[i + 2]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            px += bytes((v & 0xFF, v >> 8))
        if kind == "RGB565A8":
            px += img.getchannel("A").tobytes()
            cf = "LV_COLOR_FORMAT_RGB565A8"
        else:
            cf = "LV_COLOR_FORMAT_RGB565"
        data, stride = bytes(px), w * 2
    body = (f"static const uint8_t {name}_map[] = {{\n{hex_rows(data)}\n}};\n\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{\n        .magic = LV_IMAGE_HEADER_MAGIC,\n        .cf = {cf},\n"
            f"        .w = {w},\n        .h = {h},\n        .stride = {stride},\n    }},\n"
            f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n")
    return body


def build(area):
    src = SRC / area
    files = sorted(p for p in src.rglob("*") if p.suffix.lower() in (".svg", ".png"))
    if not files:
        print(f"{area}: no assets in {src}")
        return
    svgs = [p for p in files if p.suffix.lower() == ".svg"]
    rendered = asyncio.run(render_svgs(svgs)) if svgs else {}

    OUT.mkdir(parents=True, exist_ok=True)
    c_parts = [f"/* Generated by scripts/ui_assets/build_ui_assets.py from main/ui/assets_src/{area}. */",
               "", '#include "lvgl.h"', ""]
    h_parts = ["#pragma once", "", f"/* Generated by scripts/ui_assets/build_ui_assets.py. */", "",
               '#include "lvgl.h"', ""]
    for path in files:
        name = c_name(area, path.relative_to(src).with_suffix(""))
        if path in rendered:
            img, kind = rendered[path], "A8"
        else:
            img = Image.open(path).convert("RGBA")
            kind = "RGB565" if img.getchannel("A").getextrema()[0] == 255 else "RGB565A8"
        c_parts.append(emit(name, img, kind))
        h_parts.append(f"LV_IMAGE_DECLARE({name}); /* {img.size[0]}x{img.size[1]} {kind} */")
    (OUT / f"{area}_assets.c").write_text("\n".join(c_parts))
    (OUT / f"{area}_assets.h").write_text("\n".join(h_parts) + "\n")
    print(f"{area}: {len(files)} assets -> {OUT.relative_to(ROOT)}/{area}_assets.c")


if __name__ == "__main__":
    for a in sys.argv[1:]:
        build(a)
