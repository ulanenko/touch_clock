"""Write sim_sdkconfig.h from the project's sdkconfig, adjusted for a single-threaded host build."""
import re
import sys
from pathlib import Path

src, dst = Path(sys.argv[1]), Path(sys.argv[2])

DROP = (
    "CONFIG_LV_OS_",
    "CONFIG_LV_ATTRIBUTE_FAST_MEM_USE_IRAM",
    "CONFIG_LV_USE_DRAW_PPA",
    "CONFIG_LV_DRAW_SW_ASM",
    "CONFIG_TOUCH_CLOCK_PERF_TOUR",
    "CONFIG_SOC_",
    "CONFIG_FREERTOS",
)
OVERRIDES = {
    "CONFIG_LV_OS_NONE": "1",
    "CONFIG_LV_DRAW_SW_DRAW_UNIT_CNT": "1",
    "CONFIG_LV_CONF_SKIP": "1",
    "CONFIG_LV_USE_LOG": "1",
    "CONFIG_LV_LOG_LEVEL_WARN": "1",
    "CONFIG_LV_LOG_PRINTF": "1",
    "CONFIG_LV_DRAW_SW_ASM_NONE": "1",
}

lines = ["#pragma once", "/* Generated by sim/gen_sdkconfig.py from sdkconfig. Do not edit. */"]
for raw in src.read_text().splitlines():
    m = re.match(r"^(CONFIG_[A-Z0-9_]+)=(.*)$", raw)
    if not m:
        continue
    key, value = m.groups()
    if key.startswith(DROP) or key in OVERRIDES:
        continue
    if value == "y":
        value = "1"
    lines.append(f"#define {key} {value}")
lines += [f"#define {k} {v}" for k, v in OVERRIDES.items()]
dst.write_text("\n".join(lines) + "\n")
